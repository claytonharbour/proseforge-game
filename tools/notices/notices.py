#!/usr/bin/env python3
"""Write THIRD_PARTY_NOTICES.md from the packages the game actually ships.

Reads the restored package list (src/ProseForge.Game/obj/project.assets.json, so run a build or
`dotnet restore` first) and, for every package in the Android and iOS apps, its licence expression,
copyright line and the notice files the package itself carries (LICENSE*, THIRD-PARTY-NOTICES*).
Identical notice texts are printed once and every package that shares one points at it. The list is
generated, never typed, so a new dependency can't go uncredited; the rules tests check every
PackageReference and every bundled font is in the file.

    python3 tools/notices/notices.py           write the file
    python3 tools/notices/notices.py --check   exit 1 if the file is out of date
"""
import hashlib, json, os, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ASSETS = ROOT / "src/ProseForge.Game/obj/project.assets.json"
OUT = ROOT / "THIRD_PARTY_NOTICES.md"
PACKAGES = Path(os.environ.get("NUGET_PACKAGES", Path.home() / ".nuget/packages"))
# Build tooling: runs on the developer's machine and isn't part of the app.
BUILD_ONLY = re.compile(r"(\.Build\.Tasks|\.Resizetizer|\.ILLink\.Tasks)$")
NOTICE_FILES = re.compile(r"^(LICEN[CS]E|THIRD-PARTY-NOTICES|NOTICE)", re.I)
# The standard text of every licence a component names, for the ones that carry no notice file
# of their own (most MIT packages). A licence with no text here stops the script: add it.
STANDARD = {p.stem: p for p in (Path(__file__).parent / "texts").glob("*.txt")}

# Files we ship that don't come from a package.
BUNDLED = [{
    "name": "Open Sans (OpenSans-Regular.ttf, OpenSans-Semibold.ttf)",
    "version": "1.10",
    "licence": "Apache-2.0",
    "copyright": "Digitized data copyright © 2010-2011, Google Corporation.",
    "url": "https://fonts.google.com/specimen/Open+Sans",
    "texts": [("src/ProseForge.Game/Resources/Fonts/LICENSE.txt",
               (ROOT / "src/ProseForge.Game/Resources/Fonts/LICENSE.txt"))],
}]


def shipped_packages():
    assets = json.loads(ASSETS.read_text())
    found = set()
    for target, libs in assets["targets"].items():
        if "/" in target or not target.startswith(("net10.0-android", "net10.0-ios")):
            continue
        found |= {name for name, lib in libs.items() if lib.get("type") == "package"}
    return sorted(n for n in found if not BUILD_ONLY.search(n.split("/")[0]))


def describe(name):
    pid, version = name.split("/")
    folder = PACKAGES / pid.lower() / version.lower()
    spec = (folder / f"{pid.lower()}.nuspec").read_text(encoding="utf-8-sig")
    field = lambda tag: (m.group(1).strip() if (m := re.search(rf"<{tag}[^>]*>([^<]*)</{tag}>", spec)) else "")
    texts = [(f.name, f) for f in sorted(folder.iterdir()) if f.is_file() and NOTICE_FILES.match(f.name)]
    return {"name": pid, "version": version, "licence": field("license") or field("licenseUrl"),
            "copyright": field("copyright"), "url": field("projectUrl"), "texts": texts}


def render(entries):
    blocks, order = {}, []
    for e in entries:
        e["refs"] = []
        named = re.findall(r"[A-Za-z0-9.\-]+", e["licence"].replace(" AND ", " ").replace(" OR ", " "))
        missing = [n for n in named if n not in STANDARD]
        if missing:
            sys.exit(f"{e['name']}: no standard text for {missing} in tools/notices/texts/")
        for label, path in e["texts"] + [(f"{n} licence", STANDARD[n]) for n in named]:
            body = path.read_text(encoding="utf-8-sig", errors="replace").strip()
            key = hashlib.sha256(body.encode()).hexdigest()[:10]
            if key not in blocks:
                blocks[key] = body
                order.append(key)
            e["refs"].append(f"[{label}](#text-{key})")
    lines = [
        "# Third-party notices",
        "",
        "One More Story is built on the open-source software and fonts below. Each is used under its own",
        "licence, reproduced in full in the second half of this file. Generated by",
        "`tools/notices/notices.py` from the packages the Android and iOS apps ship; don't edit by hand.",
        "",
        "| Component | Version | Licence | Copyright | Notice texts |",
        "|---|---|---|---|---|",
    ]
    for e in entries:
        name = f"[{e['name']}]({e['url']})" if e["url"] else e["name"]
        lines.append(f"| {name} | {e['version']} | {e['licence']} | {e['copyright'].replace('|', '/')} | "
                     f"{', '.join(e['refs']) or 'see licence'} |")
    lines += ["", "## Licence and notice texts", ""]
    for key in order:
        lines += [f'<a id="text-{key}"></a>', f"### Text {key}", "", "```text", blocks[key], "```", ""]
    return "\n".join(lines) + "\n"


def main():
    if not ASSETS.exists():
        sys.exit(f"{ASSETS.relative_to(ROOT)} is missing: run `dotnet restore src/ProseForge.Game` first")
    text = render([describe(n) for n in shipped_packages()] + BUNDLED)
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit("THIRD_PARTY_NOTICES.md is out of date: run `make notices`")
        print("THIRD_PARTY_NOTICES.md is up to date")
        return
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}: {text.count(chr(10) + '| ') - 1} components")


if __name__ == "__main__":
    main()
